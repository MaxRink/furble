#!/usr/bin/env python3
"""Generate the simulator's memory-relevant sdkconfig header.

The simulator compiles production sources without ESP-IDF, so no CONFIG_*
symbol reaches them and every `#if defined(CONFIG_SPIRAM)` branch compiled out.
This script copies the memory-relevant subset of one board's sdkconfig into a
header that sim/build.sh force-includes into firmware and simulator
translation units, so those branches and the heap abort policy match the board.

Only allowlisted prefixes are emitted. Target identity (CONFIG_IDF_TARGET_*),
SoC capabilities and power symbols stay out: M5GFX, M5Unified and the host
power model key on them and must keep their host paths.

Usage: gen_sim_sdkconfig.py SDKCONFIG OUTPUT
"""

import re
import sys
from pathlib import Path

ALLOWED_PREFIXES = (
    "CONFIG_SPIRAM",
    "CONFIG_HEAP_",
    "CONFIG_FREERTOS_TASK_CREATE_ALLOW_EXT_MEM",
    "CONFIG_FREERTOS_CHECK_STACKOVERFLOW",
    "CONFIG_ESP_MAIN_TASK_STACK_SIZE",
    "CONFIG_ESP_SYSTEM_EVENT_TASK_STACK_SIZE",
    "CONFIG_ESP_TIMER_TASK_STACK_SIZE",
    "CONFIG_BT_NIMBLE_MAX_CONNECTIONS",
    "CONFIG_BT_NIMBLE_MAX_BONDS",
    "CONFIG_BT_NIMBLE_MEM_ALLOC_MODE",
    "CONFIG_BT_NIMBLE_MSYS",
    "CONFIG_BT_NIMBLE_HOST_TASK_STACK_SIZE",
    "CONFIG_ESP_WIFI_STATIC_RX_BUFFER_NUM",
    "CONFIG_ESP_WIFI_DYNAMIC_",
    "CONFIG_LWIP_TCP_SND_BUF_DEFAULT",
    "CONFIG_LWIP_TCP_WND_DEFAULT",
    "CONFIG_LWIP_TCPIP_TASK_STACK_SIZE",
    "CONFIG_MBEDTLS_SSL_IN_CONTENT_LEN",
    "CONFIG_MBEDTLS_SSL_OUT_CONTENT_LEN",
    "CONFIG_MBEDTLS_INTERNAL_MEM_ALLOC",
    "CONFIG_MBEDTLS_EXTERNAL_MEM_ALLOC",
    "CONFIG_MBEDTLS_DEFAULT_MEM_ALLOC",
    "CONFIG_MBEDTLS_DYNAMIC_BUFFER",
    "CONFIG_COMPILER_CXX_EXCEPTIONS",
    "CONFIG_COMPILER_STACK_CHECK_MODE",
)

USAGE = "Usage: gen_sim_sdkconfig.py SDKCONFIG OUTPUT"
LINE = re.compile(r"^(CONFIG_[A-Z0-9_]+)=(.*)$")


def render(sdkconfig: Path) -> str:
    lines = [
        "/* Generated by tools/gen_sim_sdkconfig.py from "
        f"{sdkconfig.name}. Do not edit. */",
        "#ifndef FURBLE_SIM_SDKCONFIG_H",
        "#define FURBLE_SIM_SDKCONFIG_H",
    ]
    for raw in sdkconfig.read_text().splitlines():
        match = LINE.match(raw.strip())
        if match is None:
            continue
        name, value = match.groups()
        if not name.startswith(ALLOWED_PREFIXES):
            continue
        if value == "y":
            value = "1"
        lines.append(f"#define {name} {value}")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main(argv: list) -> int:
    if len(argv) != 3:
        print(USAGE, file=sys.stderr)
        return 2
    sdkconfig = Path(argv[1])
    output = Path(argv[2])
    if not sdkconfig.is_file():
        print(f"sdkconfig not found: {sdkconfig}", file=sys.stderr)
        return 1
    text = render(sdkconfig)
    # Rewrite only on change so the depfile check keeps unrelated objects cached.
    if not output.is_file() or output.read_text() != text:
        output.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
