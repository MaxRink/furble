#!/usr/bin/env python3
"""Seeded memory-pressure fuzzer for the simulator.

Each seed generates one deterministic boot script: a random internal-heap
free/largest pair with WebUI and, in the MQTT build, MQTT admission. The run
must stay on the main page, keep the watchdog fed, and never print a panic,
stack-overflow or crash marker. Every furble sdkconfig aborts on a failed
allocation, so surviving a random pool proves the admission gates refuse each
service before an allocation can fail. Forced task allocation failures are not
fuzzed: they always abort, which sim/scripts/run-panic-fixtures.sh certifies.

This drives the existing simulator heap and task-create fault seams. The
expanded hardware memory model is owned by the sim-memory worktree; this driver
only adds randomized schedules on top of the shared interface.
"""
from __future__ import annotations

import argparse
import os
import random
import re
import subprocess
import sys
import tempfile
from pathlib import Path

CRASH_PATTERNS = (
    "SIM CRASH",
    "SIM PANIC",
    "Guru Meditation",
    "panic",
    "stack overflow",
    "stack canary",
    "assert failed",
    "Segmentation fault",
    "Aborted",
)

SUPERVISOR_FREE_FLOOR = 4096
SUPERVISOR_LARGEST_FLOOR = 3584


def parse_state(output: str, name: str) -> str:
    match = re.search(rf"^state {re.escape(name)} = (.*)$", output, re.MULTILINE)
    return match.group(1).strip() if match else ""


def build_script(seed: int, mqtt: bool) -> tuple[str, dict[str, object]]:
    rng = random.Random(seed)
    free_bytes = rng.choice(
        [
            0,
            rng.randint(0, 2048),
            rng.randint(2048, 8192),
            rng.randint(8192, 16384),
            rng.randint(16384, 32768),
        ]
    )
    largest = rng.randint(0, max(0, free_bytes))
    # Keep the generator's random stream stable for existing seeds: the roll
    # that used to pick a forced task failure is still drawn and discarded.
    if mqtt:
        rng.random()

    lines = [
        "# generated by tests/fuzz/memory_fuzz.py",
        f"seed heap_internal_free {free_bytes}",
        f"seed heap_internal_largest {largest}",
        "seed wifi_connected true",
        "seed web_ui true",
        "seed webui_password true",
    ]
    lines.extend(
        [
            "wait 100",
            "assert heap.active yes",
            "assert ui.page main",
            "assert platform.watchdog armed",
            # Keep the stack budgets under the memory fuzzer too: the 12 KiB
            # main task (the 8 KiB experiment overflowed after MQTT) and the
            # 3 KiB internal companion task.
            "assert mem.component.main_stack 12288",
            "assert mem.component.companion_task 3072",
            "print webui.supervisor",
            "print webui.server",
            "print webui.fail_closed",
            "print heap.free",
            "print heap.largest",
            "print heap.alloc_failures",
            # Cover the 10 s HTTPS budget retry and the MQTT retry limit. The
            # simulator advances this deadline on its virtual clock.
            "wait 16000" if mqtt else "wait 12000",
            "assert ui.page main",
            "assert platform.watchdog armed",
            "exit",
        ]
    )
    expectation = {
        "free": free_bytes,
        "largest": largest,
    }
    return "\n".join(lines) + "\n", expectation


def run_one(sim: Path, seed: int, mqtt: bool, timeout: int) -> list[str]:
    script, expectation = build_script(seed, mqtt)
    with tempfile.TemporaryDirectory(prefix="furble-memory-fuzz-") as directory:
        script_path = Path(directory) / "scenario.txt"
        script_path.write_text(script, encoding="utf-8")
        command = [str(sim), "--script", str(script_path)]
        try:
            result = subprocess.run(
                command,
                capture_output=True,
                text=True,
                timeout=timeout,
                env={
                    **os.environ,
                    "SDL_VIDEODRIVER": "dummy",
                    "SDL_AUDIODRIVER": "dummy",
                    "FURBLE_SIM_MQTT_URI": "mqtt://127.0.0.1:1",
                    "FURBLE_SIM_MQTT_FAST_RECONNECT": "1",
                },
            )
        except subprocess.TimeoutExpired:
            return [f"seed {seed}: timed out after {timeout}s"]

    output = result.stdout + result.stderr
    findings: list[str] = []
    for pattern in CRASH_PATTERNS:
        if pattern in output:
            findings.append(f"seed {seed}: crash marker '{pattern}'")
    if result.returncode != 0:
        findings.append(f"seed {seed}: exit {result.returncode}")

    supervisor = parse_state(output, "webui.supervisor")
    server = parse_state(output, "webui.server")
    fail_closed = parse_state(output, "webui.fail_closed")
    # alloc_failed is unreachable: a failed allocation aborts the run first.
    if supervisor not in {"created", "blocked", "off"}:
        findings.append(f"seed {seed}: unexpected supervisor state '{supervisor}'")
    if server not in {"running", "pending", "blocked", "off"}:
        findings.append(f"seed {seed}: unexpected server state '{server}'")
    if fail_closed not in {"yes", "no"}:
        findings.append(f"seed {seed}: unexpected fail_closed state '{fail_closed}'")

    if supervisor == "blocked" and fail_closed != "yes":
        findings.append(f"seed {seed}: blocked supervisor did not fail closed")
    if server == "blocked" and fail_closed != "yes":
        findings.append(f"seed {seed}: blocked HTTPS server did not fail closed")

    # The supervisor gate must never open below its documented floors, and a
    # gate below the floor must never allocate a task.
    free_bytes = int(expectation["free"])
    largest = int(expectation["largest"])
    if free_bytes < SUPERVISOR_FREE_FLOOR or largest < SUPERVISOR_LARGEST_FLOOR:
        if supervisor == "created":
            findings.append(
                f"seed {seed}: supervisor created below the floor "
                f"({free_bytes}/{largest})"
            )

    if findings:
        # Persist the exact failing script and command next to the report so a
        # finding is replayable without regenerating the seed table.
        failure_dir = Path(__file__).resolve().parent / "failures"
        failure_dir.mkdir(parents=True, exist_ok=True)
        failure_path = failure_dir / f"memory-seed-{seed}.txt"
        failure_path.write_text(script, encoding="utf-8")
        findings.append(f"seed {seed}: replay {sim} --script {failure_path}")
    return findings


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sim", type=Path, required=True)
    parser.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3, 4, 7, 42, 99, 1000])
    parser.add_argument("--mqtt", action="store_true")
    parser.add_argument("--timeout", type=int, default=90)
    args = parser.parse_args()

    if not args.sim.is_file():
        print(f"memory fuzz: simulator not found at {args.sim}", file=sys.stderr)
        return 2

    findings: list[str] = []
    for seed in args.seeds:
        findings.extend(run_one(args.sim, seed, args.mqtt, args.timeout))

    if findings:
        for finding in findings:
            print(f"MEMORY FUZZ FINDING [{finding}]", file=sys.stderr)
        return 1
    print(f"MEMORY FUZZ PASS seeds={len(args.seeds)} mqtt={int(args.mqtt)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
